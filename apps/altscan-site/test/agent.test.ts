import assert from 'node:assert';
import { readFileSync } from 'node:fs';
import { prefersMarkdown, homeResponse, HOME_LINK, HOME_MARKDOWN } from '../src/lib/home.ts';
import { TRAINING_BLOCKED } from '../../explorer/lib/bot-policy.ts';

let passed = 0;
async function t(name: string, fn: () => void | Promise<void>) { await fn(); passed++; console.log('ok -', name); }

const pub = (p: string) => readFileSync(new URL(`../public/${p}`, import.meta.url), 'utf8');

// prefersMarkdown: browsers stay on HTML, agents opt in
await t('prefersMarkdown: a bare text/markdown opts in', () => {
  assert.equal(prefersMarkdown('text/markdown'), true);
});
await t('prefersMarkdown: browser Accept headers stay on HTML', () => {
  assert.equal(prefersMarkdown('text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8'), false);
  assert.equal(prefersMarkdown('*/*'), false);
  assert.equal(prefersMarkdown(null), false);
});
await t('prefersMarkdown: q-values decide a mixed header', () => {
  assert.equal(prefersMarkdown('text/markdown, text/html;q=0.9'), true);
  assert.equal(prefersMarkdown('text/html, text/markdown;q=0.9'), false);
});
await t('prefersMarkdown: q=0 means not acceptable', () => {
  assert.equal(prefersMarkdown('text/markdown;q=0'), false);
});

// homeResponse: one URL, two representations, both carrying the Link header
const fakeAssets = () => {
  const seen: string[] = [];
  return {
    seen,
    async fetch(r: Request) {
      seen.push(new URL(r.url).pathname);
      return new Response('body', { headers: { 'content-type': 'text/plain; charset=utf-8', etag: '"x"' } });
    },
  };
};
await t('homeResponse: Accept text/markdown serves llms.txt as text/markdown', async () => {
  const assets = fakeAssets();
  const res = await homeResponse(new Request('https://altscan.io/', { headers: { accept: 'text/markdown' } }), assets);
  assert.deepEqual(assets.seen, [HOME_MARKDOWN]);
  assert.equal(res.headers.get('content-type'), 'text/markdown; charset=utf-8');
  assert.equal(res.headers.get('vary'), 'Accept');
  assert.equal(res.headers.get('link'), HOME_LINK);
});
await t('homeResponse: a browser gets the page asset untouched, plus Link and Vary', async () => {
  const assets = fakeAssets();
  const res = await homeResponse(new Request('https://altscan.io/', { headers: { accept: 'text/html' } }), assets);
  assert.deepEqual(assets.seen, ['/']);
  assert.equal(res.headers.get('content-type'), 'text/plain; charset=utf-8');
  assert.equal(res.headers.get('etag'), '"x"');
  assert.equal(res.headers.get('link'), HOME_LINK);
});
await t('HOME_LINK: every target is a file this site publishes', () => {
  for (const [, path] of HOME_LINK.matchAll(/<([^>]+)>/g)) {
    if (path === '/sitemap-index.xml') continue; // generated by @astrojs/sitemap at build
    assert.ok(pub(path.slice(1)).length > 0, path);
  }
});

// robots.txt: the policy llms.txt states, in the groups where it takes effect
const robots = pub('robots.txt').split('\n');
const group = (ua: string) => {
  const start = robots.indexOf(`User-agent: ${ua}`);
  assert.ok(start >= 0, `no group for ${ua}`);
  return robots.slice(start, robots.indexOf('', start));
};
await t('robots.txt: Content-Signal sits in the catch-all group, once', () => {
  assert.ok(group('*').includes('Content-Signal: ai-train=no, search=yes, ai-input=yes'));
  assert.equal(robots.filter((l) => l.startsWith('Content-Signal:')).length, 1);
});
await t('robots.txt: blocks the explorers\' training crawlers (except AhrefsBot, a load block)', () => {
  const blocked = group('GPTBot').filter((l) => l.startsWith('User-agent: ')).map((l) => l.slice(12));
  assert.deepEqual(blocked, TRAINING_BLOCKED.filter((b) => b !== 'AhrefsBot'));
  assert.ok(group('GPTBot').includes('Disallow: /'));
});

// Well-known catalogs
await t('api-catalog: RFC 9727 linkset nesting both explorers\' catalogs', () => {
  const { linkset } = JSON.parse(pub('.well-known/api-catalog'));
  assert.ok(Array.isArray(linkset) && linkset.length > 0);
  for (const e of linkset) assert.match(e.anchor, /^https:\/\//);
  const nested = linkset.flatMap((e: { 'api-catalog'?: { href: string }[] }) => e['api-catalog'] ?? []).map((l: { href: string }) => l.href);
  assert.deepEqual(nested, ['https://bnbscan.com/.well-known/api-catalog', 'https://ethscan.io/.well-known/api-catalog']);
});
await t('ai-catalog.json: well-formed entries, each with exactly one of url/data', () => {
  const c = JSON.parse(pub('.well-known/ai-catalog.json'));
  assert.equal(c.specVersion, '1.0');
  assert.ok(c.host.displayName);
  assert.ok(c.entries.length > 0);
  for (const e of c.entries) {
    assert.match(e.identifier, /^urn:air:altscan\.io:/);
    assert.ok(e.displayName && e.type);
    assert.notEqual('url' in e, 'data' in e);
  }
});
await t('_headers: catalogs get their media type and CORS', () => {
  const h = pub('_headers');
  assert.match(h, /\/\.well-known\/api-catalog\n {2}Content-Type: application\/linkset\+json\n {2}Access-Control-Allow-Origin: \*/);
  assert.match(h, /\/\.well-known\/ai-catalog\.json\n {2}Access-Control-Allow-Origin: \*/);
});

console.log(`\n${passed} passed`);
